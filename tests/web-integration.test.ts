test('browser edits a scenario copy, appends semantic reviews and configures an explicit local provider', { timeout: 20000 }, async t => {
  const workspace = await openBrowserWorkspace();
  t.after(() => workspace.close());
  const { page, api } = workspace;
  await workspace.signIn();
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await nav.getByRole('button', { name: /Scenarios/ }).click();
  await page.getByText('Create an immutable scenario copy', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Source scenario', exact: true }).selectOption('RF-001');
  await page.getByLabel('Copy title').fill('Browser-created immutable case');
  await page.getByRole('button', { name: 'Save scenario copy', exact: true }).click();
  await expect(page.getByText('New version saved. Existing suites retain their original scenario.')).toBeVisible();
  await page.getByRole('textbox', { name: 'Search scenarios' }).fill('Browser-created');
  await expect(page.locator('.scenario-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Run case →' }).click();
  await expect(page.getByRole('region', { name: 'Run inspector' })).toBeVisible();
  await nav.getByRole('button', { name: /Judge lab/ }).click();
  await page.getByLabel('Human label').selectOption('pass');
  await page.getByLabel('Reviewer note').fill('Checked the stored refund and final claim.');
  await page.getByRole('button', { name: 'Append review', exact: true }).click();
  await expect(page.locator('.review-history')).toHaveCount(1);
  await page.getByLabel('Semantic check').selectOption('injection');
  await page.getByRole('button', { name: 'Append review', exact: true }).click();
  await expect(page.locator('.review-history')).toHaveCount(2);
  const latest = api.service.suites.list('local-owner')[0];
  const execution = api.service.details(latest.id, 'local-owner')!.executions[0];
  assert.equal(execution.status, 'needs_review');
  assert.equal(execution.adjudicatedStatus, 'passed');
  await nav.getByRole('button', { name: /Settings/ }).click();
  await page.getByRole('button', { name: 'Save provider', exact: true }).click();
  await expect(page.getByText('Provider saved. Probe availability before running it. Automatic semantic acceptance remains disabled.')).toBeVisible();
  assert.equal(api.service.providers('local-owner')[0].networkMode, 'local');
  await nav.getByRole('button', { name: /Runs/ }).click();
  await expect(page.getByRole('combobox', { name: 'Agent', exact: true })).toContainText('Local Ollama');
});
