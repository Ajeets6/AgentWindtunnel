import test from 'node:test';
import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { openBrowserWorkspace } from './support/browser.ts';

test('browser launches a duplicate case, inspects real state, downloads exports and reloads saved history', { timeout: 20000 }, async t => {
  const workspace = await openBrowserWorkspace();
  t.after(() => workspace.close());
  const { page } = workspace;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await workspace.signIn();
  assert.equal(new URL(page.url()).hash, '', 'Bootstrap credentials must be removed from browser history');
  await expect(page.getByText('Find the failure before your customer does.')).toBeVisible();
  await page.getByRole('combobox', { name: 'Scenarios', exact: true }).selectOption('RF-018');
  await page.getByLabel('Use synthetic fixture judgments').check();
  await page.getByLabel('Repeats', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Run suite', exact: true }).click();
  const inspector = page.getByRole('region', { name: 'Run inspector' });
  await expect(inspector).toBeVisible();
  await expect(page.locator('.results-table tbody tr')).toHaveCount(2);
  await expect(page.locator('.results-section .outcome.completed')).toBeVisible();
  await expect(inspector.getByText('24,000', { exact: false })).toBeVisible();
  const saved = workspace.api.service.suites.list('local-owner')[0];
  assert.equal(saved.total, 2);
  assert.ok(workspace.api.service.details(saved.id, 'local-owner')!.executions.every(e => e.result?.refunds.length === 2));
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'JSON ↓' }).click();
  assert.match((await downloadPromise).suggestedFilename(), /^suite-.*\.json$/);
  await mkdir(resolve('data/qa'), { recursive: true });
  await page.screenshot({ path: resolve('data/qa/workbench-desktop.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Refund workbench', exact: true })).toBeVisible();
  await expect(page.locator('.results-table tbody tr')).toHaveCount(2);
  assert.deepEqual(errors, []);
});

test('narrow layout exposes inspector tabs, keyboard controls and no page overflow', { timeout: 20000 }, async t => {
  const workspace = await openBrowserWorkspace({ width: 390, height: 844 });
  t.after(() => workspace.close());
  const { page } = workspace;
  await workspace.signIn();
  await page.getByRole('button', { name: 'Try the duplicate-refund case' }).click();
  const inspector = page.getByRole('region', { name: 'Run inspector' });
  await expect(inspector).toBeVisible();
  const checks = page.getByRole('tab', { name: 'Checks', exact: true });
  await checks.click();
  await expect(page.getByRole('tabpanel', { name: 'Checks', exact: true })).toBeVisible();
  await expect(page.getByRole('tabpanel', { name: 'Conversation', exact: true })).not.toBeVisible();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Before → after' })).toBeFocused();
  await expect(page.getByRole('tabpanel', { name: 'Before → after' })).toBeVisible();
  await expect(page.locator('.metric.amber .metric-value')).toContainText('1');
  await page.getByRole('button', { name: 'Review', exact: true }).click();
  await expect(page.locator('.results-table tbody tr')).toHaveCount(1);
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(overflows, false);
  await page.getByRole('button', { name: 'Run suite', exact: true }).focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.getByLabel('Use synthetic fixture judgments').evaluate(element => element === document.activeElement), true);
  await mkdir(resolve('data/qa'), { recursive: true });
  await page.screenshot({ path: resolve('data/qa/workbench-mobile.png'), fullPage: true });
});

